export function getGradeLabel(gradeLevel: number) {
  return gradeNames[gradeLevel - 1] ?? `Kelas ${gradeLevel}`;
}

function rekeyQuestions(
  questions: DiagnosticQuestion[],
  targetGradeLevel: number,
  prefix: string,
) {
  return questions.map((question, index) => ({
    ...question,
    id: `g${targetGradeLevel}-${prefix}${index + 1}`,
    gradeLevel: targetGradeLevel,
    skillLevel: question.skillLevel,
    recommendationKey: question.recommendationKey.replace(
      /^G\d+_/,
      `G${targetGradeLevel}_`,
    ),
  }));
}

function makeElementaryQuestionSet(sourceGradeLevel: number) {
  const baseQuestions =
    banks[sourceGradeLevel] ?? makeUpperGradeBank(sourceGradeLevel);
  return [...baseQuestions, ...makeSupplementalBank(sourceGradeLevel)].slice(
    0,
    20,
  );
}

function makeSmpQuestionSet() {
  const kelas6Sd = makeElementaryQuestionSet(6).slice(0, 10);
  const kelas1Smp = makeSecondaryGradeBank(7).slice(0, 10);
  return [...kelas6Sd, ...kelas1Smp].slice(0, 20);
}

function makeSmaQuestionSet() {
  const smpFoundation = makeSmpQuestionSet().slice(0, 10);
  const kelas1Sma = makeSecondaryGradeBank(10).slice(0, 10);
  return [...smpFoundation, ...kelas1Sma].slice(0, 20);
}

export function getDiagnosticQuestions(gradeLevel: number) {
  // Grade 1 sudah menggunakan Diagnostic V2.
  // Jangan melewati legacy rekey/supplemental flow agar metadata tetap utuh.
  if (gradeLevel === 1) {
    return grade1DiagnosticV2;
  }

  // Grade 2-12 masih menggunakan legacy question bank sementara
  // sampai masing-masing grade dimigrasikan ke BSMATH_Gx_V1.
  if (gradeLevel === 2) {
    return rekeyQuestions(makeElementaryQuestionSet(1), gradeLevel, "sd-awal-");
  }
  if (gradeLevel <= 4) {
    return rekeyQuestions(
      makeElementaryQuestionSet(3),
      gradeLevel,
      "sd-tengah-",
    );
  }
  if (gradeLevel <= 6) {
    return rekeyQuestions(makeElementaryQuestionSet(5), gradeLevel, "sd-atas-");
  }
  if (gradeLevel <= 9) {
    return rekeyQuestions(makeSmpQuestionSet(), gradeLevel, "smp-");
  }
  return rekeyQuestions(makeSmaQuestionSet(), gradeLevel, "sma-");
}

export function getDiagnosticQuestionMap(gradeLevel: number) {
  return new Map(
    getDiagnosticQuestions(gradeLevel).map((question) => [
      question.id,
      question,
    ]),
  );
}

