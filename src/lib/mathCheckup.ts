export type DiagnosticCategory =
  | "Pemahaman Bilangan"
  | "Kelancaran Berhitung"
  | "Pecahan"
  | "Soal Cerita"
  | "Penalaran Logis";

export type DiagnosticQuestion = {
  id: string;
  gradeLevel: number;
  skillLevel: number;
  assessmentBand: "foundation" | "core" | "stretch";
  category: DiagnosticCategory;
  domain: string;
  skill: string;
  subskill: string;
  prerequisiteSkill: string;
  difficulty: "mudah" | "sedang" | "menantang";
  cognitiveType: "fluency" | "concept" | "application" | "reasoning";
  recommendationKey: string;
  misconceptionKey: string | null;
  diagnosticWeight: number;
  diagnosticVersion: string;
  prompt: string;
  options: string[];
  correctAnswer: string;
  explanation: string;
};

export type DiagnosticProfile = {
  level:
    | "Sangat Siap"
    | "Sesuai Jalur"
    | "Perlu Pendampingan"
    | "Fondasi Perlu Dikuatkan";
  tone: string;
  summary: string;
  recommendation: string[];
};

export type DiagnosticQuestionMeta = {
  skillLevel?: number;
  assessmentBand?: DiagnosticQuestion["assessmentBand"];
  domain?: string;
  skill?: string;
  subskill?: string;
  prerequisiteSkill?: string;
  cognitiveType?: DiagnosticQuestion["cognitiveType"];
  recommendationKey?: string;
  misconceptionKey?: string | null;
  diagnosticWeight?: number;
  diagnosticVersion?: string;
};

const gradeNames = Array.from(
  { length: 12 },
  (_, index) => `Kelas ${index + 1}`,
);

function defaultSkillFromCategory(category: DiagnosticCategory) {
  const map: Record<DiagnosticCategory, string> = {
    "Pemahaman Bilangan": "Number Sense",
    "Kelancaran Berhitung": "Calculation Fluency",
    Pecahan: "Fractions",
    "Soal Cerita": "Word Problem Modeling",
    "Penalaran Logis": "Logical Reasoning",
  };
  return map[category];
}

function defaultCognitiveType(
  category: DiagnosticCategory,
): DiagnosticQuestion["cognitiveType"] {
  if (category === "Kelancaran Berhitung") return "fluency";
  if (category === "Soal Cerita") return "application";
  if (category === "Penalaran Logis") return "reasoning";
  return "concept";
}

function defaultRecommendationKey(
  gradeLevel: number,
  category: DiagnosticCategory,
) {
  return `G${gradeLevel}_${defaultSkillFromCategory(category)
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, "_")}`;
}

function q(
  gradeLevel: number,
  id: string,
  category: DiagnosticCategory,
  difficulty: DiagnosticQuestion["difficulty"],
  prompt: string,
  options: string[],
  correctAnswer: string,
  explanation: string,
  meta: DiagnosticQuestionMeta = {},
): DiagnosticQuestion {
  const defaultSkill = defaultSkillFromCategory(category);
  const skill = meta.skill ?? defaultSkill;

  return {
    id: `g${gradeLevel}-${id}`,
    gradeLevel,
    skillLevel: meta.skillLevel ?? gradeLevel,
    assessmentBand: meta.assessmentBand ?? "core",
    category,
    domain: meta.domain ?? category,
    skill,
    subskill: meta.subskill ?? skill,
    prerequisiteSkill: meta.prerequisiteSkill ?? "",
    difficulty,
    cognitiveType: meta.cognitiveType ?? defaultCognitiveType(category),
    recommendationKey:
      meta.recommendationKey ?? defaultRecommendationKey(gradeLevel, category),
    misconceptionKey: meta.misconceptionKey ?? null,
    diagnosticWeight: meta.diagnosticWeight ?? 1,
    diagnosticVersion: meta.diagnosticVersion ?? "MATH_CHECKUP_V1",
    prompt,
    options,
    correctAnswer,
    explanation,
  };
}

